import {
  mkdir,
  readFile,
  writeFile,
} from 'node:fs/promises'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import {
  format,
  resolveConfig,
} from 'prettier'
import {
  createCanvas,
  loadImage,
} from '@napi-rs/canvas'

// Original Cute Screen artwork, MIT. Keep the same bold geometry in every size.
const monitorCat = 'M4 4L11 9H21L28 4V22A2 2 0 0 1 26 24H18V27H23V29H9V27H14V24H6A2 2 0 0 1 4 22Z'
const squintEyes = 'M8 14H11C11 18 14 19 16 15C18 19 21 18 21 14H24C24 21 19 23 16 19C13 23 8 21 8 14Z'
const mark = `${monitorCat}${squintEyes}`
const svg = (content, size = 32) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 32 32">
  ${content}
</svg>
`
const app = svg(
  `<rect width="32" height="32" rx="7" fill="#231F26"/>
  <path d="${mark}" fill="#FFFFFF" fill-rule="evenodd"/>`,
  512,
)
// Paint the silhouette over its stroke: the outline stays outside, preserving
// the white two-pixel foot. Do not stroke the eyes and narrow their openings.
const tray = svg(
  `<path d="${monitorCat}" fill="none" stroke="#231F26" stroke-width="2" stroke-linejoin="round"/>
  <path d="${mark}" fill="#FFFFFF" fill-rule="evenodd"/>
  <path d="${squintEyes}" fill="#231F26"/>`,
)
const template = svg(`<path d="${mark}" fill="#000000" fill-rule="evenodd"/>`)
const root = fileURLToPath(new URL('../', import.meta.url))
const save = (path, content) => writeFile(new URL(path, new URL('../', import.meta.url)), content)

// Generated inline views share the static icon geometry, with movable eyes.
const interactive = (size) => `<svg
    xmlns="http://www.w3.org/2000/svg"
    width="${size}"
    height="${size}"
    viewBox="0 0 32 32"
    data-brand-mark
    aria-hidden="true"
    focusable="false"
  >
    <rect
      width="32"
      height="32"
      rx="7"
      fill="#231F26"
    />
    <path
      d="${monitorCat}"
      fill="#FFFFFF"
    />
    <g data-brand-eyes>
      <path
        d="${squintEyes}"
        fill="#231F26"
      />
    </g>
  </svg>`

async function updateLandingBrand(path) {
  const url = new URL(path, new URL('../', import.meta.url))
  const source = await readFile(url, 'utf8')
  const region = /<!-- brand-mark:start -->[\s\S]*?<!-- brand-mark:end -->/u
  if (!region.test(source)) throw new Error(`Missing generated brand region: ${path}`)
  const updated = source.replace(region, `<!-- brand-mark:start -->\n${interactive(36)}\n<!-- brand-mark:end -->`)
  const filename = fileURLToPath(url)
  await save(path, await format(updated, { ...await resolveConfig(filename), filepath: filename }))
}

await mkdir(new URL('../packages/editor-vue/src/shell/assets/', import.meta.url), { recursive: true })
await mkdir(new URL('../apps/desktop/public/', import.meta.url), {
  recursive: true,
})
await Promise.all([
  save('logo.svg', app),
  save('logo-mark.svg', template),
  save('src-tauri/icons/foundation.svg', app),
  save('src-tauri/icons/tray.svg', tray),
  save('src-tauri/icons/tray-template.svg', template),
  save('packages/editor-vue/src/shell/assets/brand.svg', app),
  save('apps/desktop/public/favicon.svg', app),
  save('apps/landing/assets/logo.svg', app),
  save('packages/editor-vue/src/shell/assets/BrandMark.vue',
    `<!-- Generated by scripts/generate-brand-assets.mjs; edit the generator. -->\n<template>\n  ${interactive(30)}\n</template>\n`),
  updateLandingBrand('apps/landing/index.html'),
  updateLandingBrand('apps/landing/en/index.html'),
])

for (const [name, source] of [
  ['tray', tray],
  ['tray-template', template],
]) {
  const canvas = createCanvas(32, 32)
  canvas.getContext('2d').drawImage(await loadImage(Buffer.from(source)), 0, 0, 32, 32)
  await save(`src-tauri/icons/${name}.png`, canvas.toBuffer('image/png'))
}

const result = spawnSync(process.execPath, [
  fileURLToPath(import.meta.resolve('@tauri-apps/cli/tauri.js')),
  'icon',
  'src-tauri/icons/foundation.svg',
], {
  cwd: root,
  stdio: 'inherit',
})
if (result.error) throw result.error
if (result.status !== 0) throw new Error(`Tauri icon generation exited with ${result.status}`)
