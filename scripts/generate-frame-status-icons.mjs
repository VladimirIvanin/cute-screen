import {
  readFile,
  writeFile,
} from 'node:fs/promises'
import { Path2D } from '@napi-rs/canvas'

// Normalize the installed MIT Tabler SVG paths to the core renderer's M/L/C/Z dialect.
// Path2D expands elliptical arcs; quadratic-to-cubic conversion below is exact.
function commands(svg) {
  const tokens = new Path2D(svg).toSVGString().match(/[MLQCZ]|[-+]?(?:\d*\.\d+|\d+)(?:e[-+]?\d+)?/giu)
  if (!tokens) throw new Error('Empty Tabler path')
  const result = []
  let index = 0, x = 0, y = 0
  while (index < tokens.length) {
    const kind = tokens[index++]
    const size = { M: 2, L: 2, Q: 4, C: 6, Z: 0 }[kind]
    if (size === undefined) throw new Error(`Unsupported normalized path command ${kind}`)
    const values = tokens.slice(index, index + size).map(Number)
    index += size
    if (kind === 'Q') {
      const [cx, cy, endX, endY] = values
      result.push(['C', x + (cx - x) * 2 / 3, y + (cy - y) * 2 / 3,
        endX + (cx - endX) * 2 / 3, endY + (cy - endY) * 2 / 3, endX, endY])
    } else result.push([kind, ...values])
    if (size) [x, y] = values.slice(-2)
  }
  return result.map(([kind, ...values]) => [kind, ...values.map((value) => Number(value.toFixed(6)))])
}

const directory = 'packages/editor-vue/node_modules/@tabler/icons-vue'
const license = await readFile(`${directory}/LICENSE`, 'utf8')
const version = JSON.parse(await readFile(`${directory}/package.json`, 'utf8')).version
const paths = {}
for (const [name, component] of [['wifi', 'IconWifi'], ['battery', 'IconBattery3']]) {
  const source = await readFile(`${directory}/dist/esm/icons/${component}.mjs`, 'utf8')
  const match = source.match(/(\[\[.*\]\])\);/u)
  if (!match) throw new Error(`Cannot read ${component} geometry`)
  paths[name] = JSON.parse(match[1]).flatMap(([kind, attrs]) => {
    if (kind !== 'path') throw new Error(`Unsupported ${component} primitive ${kind}`)
    return commands(attrs.d)
  })
}
const array = (value) => `[\n${value.map((command) => `  ${JSON.stringify(command)},`).join('\n')}\n]`
const output = `/**
 * @license @tabler/icons-vue ${version} — wifi / battery-3
 * ${license.trim().split('\n').join('\n * ')}
 */
// Generated by scripts/generate-frame-status-icons.mjs. Do not edit contours by hand.
import type { ShapePathCommand } from '../shape-path-types'

export const tablerWifiPath = ${array(paths.wifi)} as const satisfies readonly ShapePathCommand[]
export const tablerBattery3Path = ${array(paths.battery)} as const satisfies readonly ShapePathCommand[]
`
const filename = 'packages/editor-core/src/composition/tabler-status-paths.ts'
if (process.argv.includes('--check')) {
  // The formatter expands generated arrays; compare semantic contours independently of whitespace.
  const existing = await readFile(filename, 'utf8')
  for (const [name, value] of [['tablerWifiPath', paths.wifi], ['tablerBattery3Path', paths.battery]]) {
    const declaration = existing.slice(existing.indexOf(`export const ${name} = `) + `export const ${name} = `.length)
      .split(' as const')[0].trim()
    if (JSON.stringify(JSON.parse(declaration.replaceAll("'", '"').replace(/,\s*\]/gu, ']'))) !== JSON.stringify(value)) {
      throw new Error(`${name} differs from installed Tabler ${version}; regenerate and format`)
    }
  }
} else await writeFile(filename, output)
