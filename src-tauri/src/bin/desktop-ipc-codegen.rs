use std::{
    env, fs,
    io::Write,
    path::PathBuf,
    process::{Command, ExitCode},
};

use cute_screen_desktop::{
    app::commands::error::CommandErrorV1,
    capture::{
        CaptureAction, CaptureCompletion, CaptureInvocationSource, CaptureOutcomeV2,
        CaptureRequestV1, CaptureTerminalOutcome, QuickCaptureDraftV1, QuickCaptureSelectionV1,
    },
    storage::OpenDocument,
};
use ts_rs::{Config, TS};

const HEADER: &str = "// Generated by `pnpm ipc:codegen`; do not edit.\n\n";

fn declaration<T: TS>() -> String {
    format!("export {}\n\n", T::decl(&Config::default()))
}

fn generated_bindings() -> String {
    let mut output = String::from(HEADER);
    output.push_str(&declaration::<CaptureAction>());
    output.push_str(&declaration::<CaptureInvocationSource>());
    output.push_str(&declaration::<CaptureRequestV1>());
    output.push_str(&declaration::<CaptureCompletion>());
    output.push_str(&declaration::<CaptureTerminalOutcome>());
    output.push_str(&declaration::<OpenDocument>());
    output.push_str(&declaration::<CaptureOutcomeV2>());
    output.push_str(&declaration::<QuickCaptureSelectionV1>());
    output.push_str(&declaration::<QuickCaptureDraftV1>());
    output.push_str(&declaration::<CommandErrorV1>());
    output
}

fn output_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../apps/desktop/src/generated/desktop-ipc.ts")
}

fn formatted_bindings() -> Result<String, String> {
    let mut temporary = tempfile::Builder::new()
        .suffix(".ts")
        .tempfile()
        .map_err(|error| error.to_string())?;
    temporary
        .write_all(generated_bindings().as_bytes())
        .map_err(|error| error.to_string())?;
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..");
    let status = Command::new("pnpm")
        .args(["exec", "prettier"])
        .arg(temporary.path())
        .arg("--config")
        .arg(root.join(".prettierrc.json"))
        .arg("--write")
        .current_dir(root)
        .status()
        .map_err(|error| format!("cannot run prettier: {error}"))?;
    if !status.success() {
        return Err("prettier failed while formatting desktop IPC bindings".to_owned());
    }
    fs::read_to_string(temporary.path()).map_err(|error| error.to_string())
}

fn main() -> ExitCode {
    let generated = match formatted_bindings() {
        Ok(generated) => generated,
        Err(error) => {
            eprintln!("cannot generate desktop IPC bindings: {error}");
            return ExitCode::FAILURE;
        }
    };
    let destination = output_path();
    if env::args().any(|argument| argument == "--check") {
        return match fs::read_to_string(&destination) {
            Ok(current) if current == generated => ExitCode::SUCCESS,
            Ok(_) => {
                eprintln!("desktop IPC bindings are stale; run `pnpm ipc:codegen`");
                ExitCode::FAILURE
            }
            Err(error) => {
                eprintln!("cannot read {}: {error}", destination.display());
                ExitCode::FAILURE
            }
        };
    }
    match fs::write(&destination, generated) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("cannot write {}: {error}", destination.display());
            ExitCode::FAILURE
        }
    }
}
